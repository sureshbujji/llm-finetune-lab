"""Evaluate base model vs LoRA-adapted model on the held-out set.
For each eval example the model greedily generates a severity label from the
prompt; predictions are parsed and scored (accuracy + per-class P/R/F1).
Writes reports/finetune_report.md with the before/after delta.

  python src/eval_before_after.py --smoke    # 4 eval examples (CI)
  python src/eval_before_after.py            # full 20-example eval
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from src.adapter import load_adapter
from src.metrics import accuracy, per_class_prf
from src.model import build_base_model, build_tokenizer_for_source
from src.prompts import LABELS, build_prompt
from src.train import load_examples


def parse_prediction(text: str) -> str | None:
    """Earliest severity label word in generated text (word-boundary match).

    Word boundaries matter: without them 'slow' parses as 'Low'.
    Earliest-match matters: the model may ramble past the answer, so the
    first label word in *text order* is the prediction.
    """
    best: str | None = None
    best_idx: int | None = None
    for label in LABELS:
        m = re.search(r"\b" + label.lower() + r"\b", text.lower())
        if m and (best_idx is None or m.start() < best_idx):
            best, best_idx = label, m.start()
    return best


def generate_label(model, tokenizer, prompt: str, max_new_tokens: int = 10) -> str:
    import torch

    model.eval()
    input_ids = torch.tensor([tokenizer.encode(prompt)], dtype=torch.long)
    with torch.no_grad():
        out = model.generate(
            input_ids,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=getattr(tokenizer, "eos_token_id", None),
        )
    new_tokens = out[0][input_ids.shape[1]:].tolist()
    return tokenizer.decode(new_tokens)


def evaluate(model, tokenizer, examples: list[dict]) -> tuple[list[str], list[str | None], list[str]]:
    y_true, y_pred, raw = [], [], []
    for ex in examples:
        prompt = build_prompt(ex["title"], ex["description"])
        gen = generate_label(model, tokenizer, prompt)
        y_true.append(ex["severity"])
        y_pred.append(parse_prediction(gen))
        raw.append(gen)
    return y_true, y_pred, raw


def render_report(
    y_true, y_pred_base, y_pred_lora, raw_base, raw_lora,
    examples, meta: dict,
) -> str:
    acc_base = accuracy(y_true, y_pred_base)
    acc_lora = accuracy(y_true, y_pred_lora)
    prf_base = per_class_prf(y_true, y_pred_base, LABELS)
    prf_lora = per_class_prf(y_true, y_pred_lora, LABELS)

    def row(label):
        b, a = prf_base[label], prf_lora[label]
        return (
            f"| {label} | {b['precision']:.2f} | {b['recall']:.2f} | {b['f1']:.2f} "
            f"| {a['precision']:.2f} | {a['recall']:.2f} | {a['f1']:.2f} "
            f"| {int(b['support'])} |"
        )

    lines = [
        "# Fine-tune report: bug-severity classification (LoRA)",
        "",
        f"Generated: {meta['generated_at_utc']} UTC",
        f"Command: `{meta['command']}`",
        "",
        "> Honesty note: this report was generated by the fully-offline path —",
        "> a randomly-initialized tiny GPT-2 (2 layers, seed 123) trained with",
        "> LoRA on 50 synthetic bug reports on CPU. No pretrained weights, no",
        "> GPU, no network. It demonstrates the *methodology* (before/after eval",
        "> with a held-out set); absolute scores are toy-scale, not SOTA claims.",
        "",
        "## Setup",
        "",
        f"- Model source: `{meta['model_source']}` (tiny GPT-2, {meta['total_params']:,} params)",
        f"- LoRA: r={meta['lora_r']}, alpha={meta['lora_alpha']}, "
        f"dropout={meta['lora_dropout']}, target_modules={', '.join(meta['lora_targets'])}",
        f"- Trainable params: {meta['trainable_params']:,} "
        f"({100.0 * meta['trainable_params'] / meta['total_params']:.2f}% of model)",
        f"- Training: {meta['epochs']} epochs x {meta['n_train']} examples, "
        f"batch {meta['batch_size']}, lr {meta['lr']}, seed {meta['seed']}",
        f"- Eval: {len(y_true)} held-out examples (data/eval.jsonl), greedy decode",
        "",
        "## Results",
        "",
        f"- Base accuracy: **{acc_base:.2f}**",
        f"- LoRA accuracy: **{acc_lora:.2f}**",
        f"- Delta: **{acc_lora - acc_base:+.2f}**",
        "",
        "| Severity | Base P | Base R | Base F1 | LoRA P | LoRA R | LoRA F1 | Support |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(label) for label in LABELS]
    lines += [
        "",
        "## Error analysis (LoRA model)",
        "",
    ]
    wrong = [
        (t, p, g, ex["title"])
        for t, p, g, ex in zip(y_true, y_pred_lora, raw_lora, examples)
        if t != p
    ]
    if wrong:
        lines.append(f"{len(wrong)} misclassified of {len(y_true)}:")
        for t, p, g, title in wrong[:10]:
            lines.append(f"- true={t} pred={p} generated={g.strip()!r} ({title})")
    else:
        lines.append("No misclassifications on the held-out set.")
    lines += [
        "",
        "## What I'd change on a real GPU run",
        "",
        "- Start from pretrained weights (`--model-source pretrained`) instead of",
        "  random init: the base model then already knows language, and LoRA",
        "  teaches it the task format + domain vocabulary.",
        "- Sweep r in {8, 16, 32} and lr in {1e-4, 5e-4, 1e-3} with a real",
        "  validation split and early stopping; keep the best by eval F1.",
        "- Add target modules (q/k/v/o for LLaMA-family) if r=8 underfits.",
        "- Replace greedy single-label generation with log-likelihood scoring",
        "  over the four label strings — more stable than free generation.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Eval base vs LoRA model.")
    parser.add_argument("--smoke", action="store_true",
                        help="eval on 4 examples (for CI)")
    parser.add_argument("--model-source", choices=["random", "pretrained"],
                        default="random")
    parser.add_argument("--seed", type=int, default=123,
                        help="must match the seed used in train.py")
    parser.add_argument("--eval-file", default="data/eval.jsonl")
    parser.add_argument("--vocab", default="data/vocab.json")
    parser.add_argument("--adapter-dir", default="adapters/lora-severity")
    parser.add_argument("--report", default="reports/finetune_report.md")
    args = parser.parse_args()

    import torch

    torch.manual_seed(args.seed)
    tokenizer, vocab_size = build_tokenizer_for_source(args.model_source, args.vocab)
    examples = load_examples(args.eval_file)
    if args.smoke:
        examples = examples[:4]

    print("evaluating base model...")
    base_model = build_base_model(args.model_source, vocab_size, args.seed)
    y_true, y_pred_base, raw_base = evaluate(base_model, tokenizer, examples)

    print("evaluating LoRA model...")
    lora_model = load_adapter(
        build_base_model(args.model_source, vocab_size, args.seed), args.adapter_dir
    )
    _, y_pred_lora, raw_lora = evaluate(lora_model, tokenizer, examples)

    # Adapter config for the report header.
    with open(os.path.join(args.adapter_dir, "training_config.json")) as f:
        train_cfg = json.load(f)
    # NB: PeftModel.from_pretrained loads adapters frozen for inference, so
    # the trainable count comes from the training run's own record.
    trainable = train_cfg["trainable_params"]
    total = sum(p.numel() for p in lora_model.parameters())

    meta = {
        "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).strftime(
            "%Y-%m-%d %H:%M"),
        "command": " ".join(sys.argv),
        "model_source": args.model_source,
        "total_params": total,
        "trainable_params": trainable,
        "lora_r": train_cfg["lora"]["r"],
        "lora_alpha": train_cfg["lora"]["lora_alpha"],
        "lora_dropout": train_cfg["lora"]["lora_dropout"],
        "lora_targets": train_cfg["lora"]["target_modules"],
        "epochs": train_cfg["epochs"],
        "n_train": train_cfg["n_train"],
        "batch_size": train_cfg["batch_size"],
        "lr": train_cfg["lr"],
        "seed": args.seed,
    }
    report = render_report(
        y_true, y_pred_base, y_pred_lora, raw_base, raw_lora, examples, meta
    )
    os.makedirs(os.path.dirname(args.report) or ".", exist_ok=True)
    with open(args.report, "w") as f:
        f.write(report)

    acc_base = accuracy(y_true, y_pred_base)
    acc_lora = accuracy(y_true, y_pred_lora)
    print(f"base acc={acc_base:.2f} lora acc={acc_lora:.2f} "
          f"delta={acc_lora - acc_base:+.2f}")
    print(f"report written to {args.report}")


if __name__ == "__main__":
    main()
